use std::borrow::Cow;
use std::io::Cursor;
use std::panic::catch_unwind;

// The initial version provides controlled self-tests only; business data interfaces belong to the image module.
#[unsafe(no_mangle)]
pub extern "C" fn pebril_native_abi() -> u32 { 1 }

fn probe_svg() -> Result<(), String> {
    let input = br#"<svg xmlns="http://www.w3.org/2000/svg" width="2" height="2"><script>alert(1)</script><rect width="2" height="2" onload="alert(1)"/></svg>"#;
    let mut output = Vec::new();
    svg_hush::Filter::new().filter(Cursor::new(input), &mut output).map_err(|e| e.to_string())?;
    let text = String::from_utf8(output).map_err(|e| e.to_string())?;
    if !text.contains("rect") || text.contains("script") || text.contains("onload") { return Err("SVG sanitization self-test failed".into()); }
    let bad = b"<svg xmlns='http://www.w3.org/2000/svg'><rect>";
    if svg_hush::Filter::new().filter(Cursor::new(bad), Vec::new()).is_ok() { return Err("Malformed SVG was not rejected".into()); }
    Ok(())
}
fn probe_gif() -> Result<(), String> {
    let mut output = Vec::new();
    {
        let mut encoder = gif::Encoder::new(&mut output, 2, 2, &[255,0,0, 0,0,255]).map_err(|e| e.to_string())?;
        encoder.set_repeat(gif::Repeat::Infinite).map_err(|e| e.to_string())?;
        for index in [0u8, 1u8] {
            let frame = gif::Frame { width:2, height:2, delay:5,
                dispose:gif::DisposalMethod::Keep,
                buffer:Cow::Owned(vec![index;4]), ..gif::Frame::default() };
            encoder.write_frame(&frame).map_err(|e|e.to_string())?;
        }
        encoder.into_inner().map_err(|e|e.to_string())?;
    }
    let mut options = gif::DecodeOptions::new(); options.set_color_output(gif::ColorOutput::RGBA);
    let mut decoder = options.read_info(Cursor::new(&output)).map_err(|e| e.to_string())?;
    if decoder.width()!=2 || decoder.height()!=2 || decoder.repeat()!=gif::Repeat::Infinite { return Err("Invalid GIF dimensions or loop count".into()); }
    let mut count=0;
    while let Some(frame)=decoder.read_next_frame().map_err(|e|e.to_string())? {
        if frame.delay!=5 || frame.width!=2 || frame.height!=2 || frame.buffer.len()!=16 { return Err("Invalid GIF frame information".into()); }
        count+=1;
    }
    if count!=2 { return Err("Invalid GIF frame count".into()); }
    Ok(())
}
#[unsafe(no_mangle)]
pub extern "C" fn pebril_native_probe() -> u32 {
    catch_unwind(|| {
        let mut bits=0;
        if probe_svg().is_ok() { bits|=1; }
        if probe_gif().is_ok() { bits|=2; }
        bits
    }).unwrap_or(0)
}

#[cfg(test)]
mod tests {
    #[test]
    fn native_library_contract() {
        assert_eq!(super::pebril_native_abi(), 1);
        super::probe_svg().expect("SVG sanitization and malformed-input rejection");
        super::probe_gif().expect("GIF frame timing and looping");
        assert_eq!(super::pebril_native_probe(), 3);
    }
}

use std::ffi::{CStr, c_char};
use std::fs::File;
use std::io::BufReader;

// Paths are generated by the parent; this ABI is called only inside its validation child.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn pebril_verify_file(input: *const c_char, output: *const c_char,
    svg: u32, max_pixels: u64, max_bytes: u64, width: *mut u32, height: *mut u32, frames: *mut u32) -> u32 {
    catch_unwind(|| -> Result<(), String> {
        let input = unsafe { CStr::from_ptr(input) }.to_str().map_err(|e| e.to_string())?;
        let output = unsafe { CStr::from_ptr(output) }.to_str().map_err(|e| e.to_string())?;
        if svg != 0 {
            let source = File::open(input).map_err(|e| e.to_string())?;
            let mut target = File::create(output).map_err(|e| e.to_string())?;
            svg_hush::Filter::new().filter(BufReader::new(source), LimitedWriter { inner: &mut target, remaining: max_bytes }).map_err(|e| e.to_string())?;
            target.sync_all().map_err(|e| e.to_string())?;
            unsafe { *width=0; *height=0; *frames=1; }
        } else {
            let source = File::open(input).map_err(|e| e.to_string())?;
            let mut options = gif::DecodeOptions::new();
            options.set_color_output(gif::ColorOutput::Indexed);
            options.check_frame_consistency(true);
            options.check_lzw_end_code(true);
            let mut decoder=options.read_info(BufReader::new(source)).map_err(|e| e.to_string())?;
            let w=u64::from(decoder.width()); let h=u64::from(decoder.height());
            if w==0 || h==0 || w*h>max_pixels { return Err("GIF pixel limit exceeded".into()); }
            let global_palette=decoder.global_palette().map(<[u8]>::to_vec);
            let mut count=0u64;
            while let Some(frame)=decoder.read_next_frame().map_err(|e| e.to_string())? {
                validate_gif_pixels(frame,global_palette.as_deref())?;
                count+=1;
                if count>max_pixels/(w*h) { return Err("GIF total pixel limit exceeded".into()); }
            }
            if count==0 { return Err("GIF contains no frames".into()); }
            unsafe { *width=w as u32; *height=h as u32; *frames=count as u32; }
        }
        Ok(())
    }).map(|r| u32::from(r.is_ok())).unwrap_or(0)
}

struct LimitedWriter<W> { inner: W, remaining: u64 }
impl<W: std::io::Write> std::io::Write for LimitedWriter<W> {
    fn write(&mut self, bytes: &[u8]) -> std::io::Result<usize> {
        if bytes.len() as u64 > self.remaining { return Err(std::io::Error::other("Sanitized SVG byte limit exceeded")); }
        let written=self.inner.write(bytes)?; self.remaining-=written as u64; Ok(written)
    }
    fn flush(&mut self) -> std::io::Result<()> { self.inner.flush() }
}

fn validate_gif_pixels(frame: &gif::Frame<'_>, global_palette: Option<&[u8]>) -> Result<(),String> {
    let palette=frame.palette.as_deref().or(global_palette).ok_or("GIF has no color palette")?;
    let colors=palette.len()/3;
    if colors==0 || frame.buffer.iter().any(|index|usize::from(*index)>=colors) { return Err("GIF contains invalid color indices".into()); }
    Ok(())
}
#[cfg(test)]
mod upload_tests {
    #[test]
    fn gif_color_indices_must_exist_in_the_active_palette() {
        let palette=[255,0,0,0,0,255];
        let mut frame=gif::Frame { width:2,height:2,buffer:std::borrow::Cow::Owned(vec![0,1,0,1]),..gif::Frame::default() };
        assert!(super::validate_gif_pixels(&frame,Some(&palette)).is_ok());
        frame.buffer=std::borrow::Cow::Owned(vec![0,2,0,1]);
        assert!(super::validate_gif_pixels(&frame,Some(&palette)).is_err());
        assert!(super::validate_gif_pixels(&frame,None).is_err());
    }
}
