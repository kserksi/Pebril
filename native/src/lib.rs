use std::ffi::{CStr, c_char};
use std::fs::File;
use std::io::BufReader;

// Paths are generated by the parent; this ABI is called only inside its validation child.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn pebril_verify_file(input: *const c_char, output: *const c_char,
    svg: u32, max_pixels: u64, max_bytes: u64, width: *mut u32, height: *mut u32, frames: *mut u32) -> u32 {
    catch_unwind(|| -> Result<(), String> {
        let input = unsafe { CStr::from_ptr(input) }.to_str().map_err(|e| e.to_string())?;
        let output = unsafe { CStr::from_ptr(output) }.to_str().map_err(|e| e.to_string())?;
        if svg != 0 {
            let source = File::open(input).map_err(|e| e.to_string())?;
            let mut target = File::create(output).map_err(|e| e.to_string())?;
            svg_hush::Filter::new().filter(BufReader::new(source), LimitedWriter { inner: &mut target, remaining: max_bytes }).map_err(|e| e.to_string())?;
            target.sync_all().map_err(|e| e.to_string())?;
            unsafe { *width=0; *height=0; *frames=1; }
        } else {
            let source = File::open(input).map_err(|e| e.to_string())?;
            let mut options = gif::DecodeOptions::new();
            options.set_color_output(gif::ColorOutput::Indexed);
            options.check_frame_consistency(true);
            options.check_lzw_end_code(true);
            let mut decoder=options.read_info(BufReader::new(source)).map_err(|e| e.to_string())?;
            let w=u64::from(decoder.width()); let h=u64::from(decoder.height());
            if w==0 || h==0 || w*h>max_pixels { return Err("GIF pixel limit exceeded".into()); }
            let global_palette=decoder.global_palette().map(<[u8]>::to_vec);
            let mut count=0u64;
            while let Some(frame)=decoder.read_next_frame().map_err(|e| e.to_string())? {
                validate_gif_pixels(frame,global_palette.as_deref())?;
                count+=1;
                if count>max_pixels/(w*h) { return Err("GIF total pixel limit exceeded".into()); }
            }
            if count==0 { return Err("GIF contains no frames".into()); }
            unsafe { *width=w as u32; *height=h as u32; *frames=count as u32; }
        }
        Ok(())
    }).map(|r| u32::from(r.is_ok())).unwrap_or(0)
}

struct LimitedWriter<W> { inner: W, remaining: u64 }
impl<W: std::io::Write> std::io::Write for LimitedWriter<W> {
    fn write(&mut self, bytes: &[u8]) -> std::io::Result<usize> {
        if bytes.len() as u64 > self.remaining { return Err(std::io::Error::other("Sanitized SVG byte limit exceeded")); }
        let written=self.inner.write(bytes)?; self.remaining-=written as u64; Ok(written)
    }
    fn flush(&mut self) -> std::io::Result<()> { self.inner.flush() }
}

fn validate_gif_pixels(frame: &gif::Frame<'_>, global_palette: Option<&[u8]>) -> Result<(),String> {
    let palette=frame.palette.as_deref().or(global_palette).ok_or("GIF has no color palette")?;
    let colors=palette.len()/3;
    if colors==0 || frame.buffer.iter().any(|index|usize::from(*index)>=colors) { return Err("GIF contains invalid color indices".into()); }
    Ok(())
}
